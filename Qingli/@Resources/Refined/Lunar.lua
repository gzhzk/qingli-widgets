local function leap(y) return y%4==0 and (y%100~=0 or y%400==0) end
local function ordinal(y,m,d)
    if type(y)~='number' or type(m)~='number' or type(d)~='number'
        or y~=math.floor(y) or m~=math.floor(m) or d~=math.floor(d)
        or y<1901 or y>2101 or m<1 or m>12 then return nil end
    local limit=monthDays[m]+((m==2 and leap(y)) and 1 or 0)
    if d<1 or d>limit then return nil end
    local prev=y-1
    local n=365*prev+math.floor(prev/4)-math.floor(prev/100)+math.floor(prev/400)+d-1
    for i=1,m-1 do n=n+monthDays[i]+((i==2 and leap(y)) and 1 or 0) end
    return n
end
local function monthLength(row,m) return 29+math.floor(row[3]/2^(m-1))%2 end
local function convert(y,m,d)
    local n=ordinal(y,m,d)
    if not n or n<years[1][1] then return nil end
