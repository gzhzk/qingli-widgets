    while lo<hi do local mid=math.ceil((lo+hi)/2);if years[mid][1]<=n then lo=mid else hi=mid-1 end end
    local row=years[lo];local remaining=n-row[1]
    local count=row[2]>0 and 13 or 12
    for i=1,count do
        local length=monthLength(row,i)
        if remaining<length then
            local actual=i-((row[2]>0 and i>=row[2]) and 1 or 0)
            return {year=1900+lo,month=actual,day=remaining+1,isLeap=(i==row[2])}
        end
        remaining=remaining-length
    end
    return nil
end
